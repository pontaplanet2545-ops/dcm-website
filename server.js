app.post("/api/chat", async (req, res) => {

    try {

        const message =
            typeof req.body?.message === "string"
                ? req.body.message.trim()
                : "";

        if (!message) {

            return res.status(400).json({
                error: "กรุณาพิมพ์ข้อความก่อนครับ"
            });

        }


        /*
         * ถ้ายังไม่ได้ใส่ OPENAI_API_KEY
         * ใช้ fallback ตอบก่อน
         */

        if (!openai) {

            return res.json({
                reply: fallbackAnswer(message)
            });

        }


        /* =================================================
           ส่งคำถามไป OpenAI
        ================================================= */

        const response = await openai.responses.create({

            model: process.env.OPENAI_MODEL || "gpt-5-mini",

            instructions: DCM_KNOWLEDGE,

            input: [
                {
                    role: "user",
                    content: message
                }
            ],

            max_output_tokens: 700

        });


        let answer = response.output_text;


        /* =================================================
           ป้องกันคำตอบว่าง
        ================================================= */

        if (!answer || !answer.trim()) {

            answer = fallbackAnswer(message);

        }


        return res.json({

            reply: answer.trim()

        });

    }


    /* =====================================================
       ERROR
    ===================================================== */

    catch (error) {

        console.error("DCM Assistant Error:");

        console.error(error);


        return res.status(500).json({

            error: "ระบบ AI ไม่สามารถตอบได้ในขณะนี้ครับ"

        });

    }

});


