function getCachedAnswer(message) {

    const key = normalizeText(message);

    const cached = answerCache.get(key);

    if (!cached) {
        return null;
    }

    if (
        Date.now() - cached.time >
        CACHE_TIME
    ) {

        answerCache.delete(key);

        return null;

    }

    return cached.answer;

}


function setCachedAnswer(message, answer) {

    const key = normalizeText(message);

    answerCache.set(
        key,
        {
            answer,
            time: Date.now()
        }
    );

}


