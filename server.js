app.use(express.json({
    limit: "1mb"
}));

app.use(express.static(__dirname));


// =====================================================
// HEALTH CHECK
// =====================================================

app.get("/api/health", (req, res) => {

    res.json({

        ok: true,

        service: "DCM Assistant",

        provider: "Google Gemini",

        model: GEMINI_MODEL,

        geminiEnabled: Boolean(GEMINI_API_KEY)

    });

});


// =====================================================
// GEMINI CHAT API
// =====================================================

app.post("/api/chat", async (req, res) => {

    try {

        const message =
            String(req.body?.message || "").trim();


        // -------------------------------
        // ตรวจสอบข้อความ
        // -------------------------------

        if (!message) {

            return res.status(400).json({

                success: false,

                error:
                    "กรุณาพิมพ์ข้อความก่อนครับ"

            });

        }


        // -------------------------------
        // ตรวจสอบ API KEY
        // -------------------------------

        if (!genAI) {

            return res.status(503).json({

                success: false,

                error:
                    "ยังไม่ได้ตั้งค่า GEMINI_API_KEY บน Render"

            });

        }


        // -------------------------------
        // สร้าง Gemini Model
        // -------------------------------

        const model =
            genAI.getGenerativeModel({

                model: GEMINI_MODEL,

                systemInstruction:
                    DCM_KNOWLEDGE

            });


        // -------------------------------
        // ส่งคำถามไป Gemini
        // -------------------------------

        const result =
            await model.generateContent({

                contents: [

                    {

                        role: "user",

                        parts: [

                            {
                                text: message
                            }

                        ]

                    }

                ]

            });


        // -------------------------------
        // อ่านคำตอบ
        // -------------------------------

        const reply =
            result?.response?.text?.();


        if (!reply) {

            return res.status(500).json({

                success: false,

                error:
                    "Gemini ไม่ได้ส่งข้อความตอบกลับ"

            });

        }


        // -------------------------------
        // ส่งกลับไปหน้าเว็บไซต์
        // -------------------------------

        return res.json({

            success: true,

            reply: reply

        });

    }

    catch (error) {

        console.error(
            "=============================="
        );

        console.error(
            "Gemini Error:"
        );

        console.error(error);

        console.error(
            "=============================="
        );


        return res.status(500).json({

            success: false,

            error:
                "เกิดข้อผิดพลาดในการเชื่อมต่อ Gemini",

            detail:
                process.env.NODE_ENV === "development"
                    ? error.message
                    : undefined

        });

    }

});


// =====================================================
// FRONTEND
// =====================================================

app.get("*", (req, res) => {

    res.sendFile(
        path.join(
            __dirname,
            "index.html"
        )
    );

});


// =====================================================
// START SERVER
// =====================================================

app.listen(PORT, () => {

    console.log(
        "======================================"
    );

    console.log(
        "DCM Assistant Server Started"
    );

    console.log(
        `Port: ${PORT}`
    );

    console.log(
        `Gemini enabled: ${Boolean(GEMINI_API_KEY)}`
    );

    console.log(
        `Gemini model: ${GEMINI_MODEL}`
    );

    console.log(
        "======================================"

    );

});
