function isGreeting(message) {

    const text = message
        .toLowerCase()
        .replace(/\s+/g, "");

    const greetings = [
        "สวัสดี",
        "สวัสดีครับ",
        "สวัสดีค่ะ",
        "หวัดดี",
        "หวัดดีครับ",
        "หวัดดีพี่",
        "ดีครับ",
        "ดีพี่",
        "ฮัลโหล",
        "hello",
        "hi",
        "hey",
        "โย่ว",
        "พี่ครับ",
        "พี่คับ",
        "พี่อยู่ไหม",
        "อยู่ไหม",
        "อยู่ป่าว",
        "อยู่ไหมครับ"
    ];

    return greetings.some(word => text.includes(word));
}


function isThanks(message) {

    const text = message
        .toLowerCase()
        .replace(/\s+/g, "");

    const words = [
        "ขอบคุณ",
        "ขอบคุณครับ",
        "ขอบคุณค่ะ",
        "ขอบใจ",
        "ขอบใจพี่",
        "ขอบคุณมาก",
        "แต๊ง",
        "thanks",
        "thankyou",
        "โอเคขอบคุณ"
    ];

    return words.some(word => text.includes(word));
}


function isGoodbye(message) {

    const text = message
        .toLowerCase()
        .replace(/\s+/g, "");

    const words = [
        "บาย",
        "บ๊ายบาย",
        "ไปก่อนนะ",
        "ไปก่อนครับ",
        "ไปละ",
        "ไปแล้ว",
        "ไว้คุยกัน",
        "ไว้ถามใหม่",
        "แค่นี้ครับ",
        "ไม่มีแล้ว",
        "จบแล้ว"
    ];

    return words.some(word => text.includes(word));
}


