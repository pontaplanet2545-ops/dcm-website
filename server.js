app.get("/api/health", (req, res) => {

    res.json({
        ok: true,
        service: "DCM Assistant API",
        provider: "Google Gemini",
        geminiEnabled: Boolean(GEMINI_API_KEY),
        model: GEMINI_MODEL
    });

});


// ===============================
// Chat API
// ===============================

app.post("/api/chat", async (req, res) => {

    try {

        const message = String(
            req.body?.message || ""
        ).trim();

        if (!message) {

            return res.status(400).json({
                error: "กรุณาพิมพ์ข้อความก่อนครับ"
            });

        }


        if (!GEMINI_API_KEY || !ai) {

            return res.status(503).json({
                error: "ยังไม่ได้เชื่อมต่อ Gemini API กรุณาตรวจสอบ GEMINI_API_KEY บน Render"
            });

        }


        const prompt = `
ข้อมูลหลักสูตร DCM:

${DCM_KNOWLEDGE}


คำถามจากผู้ใช้:

${message}


โปรดตอบคำถามโดยอ้างอิงข้อมูลหลักสูตรด้านบน
ห้ามแต่งข้อมูลที่ไม่มีอยู่ในฐานความรู้
ตอบให้ตรงคำถาม กระชับ และอ่านง่าย
`;


        const response = await ai.models.generateContent({

            model: GEMINI_MODEL,

            contents: prompt,

            config: {

                temperature: 0.3,

                maxOutputTokens: 1200

            }

        });


        const reply =
            response?.text ||
            "ขออภัยครับ ตอนนี้ยังไม่สามารถสร้างคำตอบได้";


        return res.json({

            success: true,

            reply: reply,

            model: GEMINI_MODEL

        });

    } catch (error) {

        console.error(
            "Gemini API Error:",
            error
        );


        return res.status(500).json({

            success: false,

            error: "เกิดข้อผิดพลาดในการเชื่อมต่อ Gemini API"

        });

    }

});


// ===============================
