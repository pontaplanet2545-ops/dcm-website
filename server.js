app.get("/api/health", (req, res) => {

    res.json({

        status: "ok",

        aiConfigured:
            Boolean(process.env.OPENAI_API_KEY),

        model:
            process.env.OPENAI_MODEL || "gpt-5-mini"

    });

});


/* =====================================================
   AI CHAT
===================================================== */

app.post("/api/chat", async (req, res) => {

    try {

        const message =
            String(req.body?.message || "").trim();


        /* ตรวจสอบคำถาม */

        if (!message) {

            return res.status(400).json({

                error:
                    "กรุณาพิมพ์คำถามก่อนครับ"

            });

        }


        /* จำกัดความยาว */

        if (message.length > 4000) {

            return res.status(400).json({

                error:
                    "คำถามยาวเกินไปครับ กรุณาย่อคำถามลง"

            });

        }


        /* ตรวจ API Key */

        if (!openai) {

            return res.status(503).json({

                error:
                    "ระบบ AI ยังไม่ได้ตั้งค่า OPENAI_API_KEY บนเซิร์ฟเวอร์ครับ"

            });

        }


        /* ส่งคำถามไป OpenAI */

        const response =
            await openai.responses.create({

                model:
                    process.env.OPENAI_MODEL ||
                    "gpt-5-mini",

                instructions:
                    DCM_KNOWLEDGE,

                input:
                    message,

                max_output_tokens:
                    700

            });


        const reply =
            response.output_text?.trim();


        /* ตรวจคำตอบ */

        if (!reply) {

            return res.status(502).json({

                error:
                    "AI ไม่ได้ส่งคำตอบกลับมาครับ"

            });

        }


        /* ส่งคำตอบกลับไปหน้าเว็บ */

        res.json({

            reply: reply

        });


    } catch (error) {

        console.error(
            "DCM AI ERROR:",
            error
        );


        res.status(500).json({

            error:
                "เกิดข้อผิดพลาดในการเชื่อมต่อ AI ครับ"

        });

    }

});


