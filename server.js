const answerCache = new Map();

const CACHE_TIME =
    15 * 60 * 1000;


// =====================================================
// NORMALIZE
// =====================================================

function normalizeText(text) {

    return String(text || "")
        .toLowerCase()
        .replace(/\s+/g, "")
        .trim();

}


// =====================================================
// CACHE GET
// =====================================================

function getCache(message) {

    const key =
        normalizeText(message);

    const item =
        answerCache.get(key);

    if (!item) {
        return null;
    }

    if (
        Date.now() - item.time >
        CACHE_TIME
    ) {

        answerCache.delete(key);

        return null;

    }

    return item.answer;

}


// =====================================================
// CACHE SET
// =====================================================

function setCache(message, answer) {

    const key =
        normalizeText(message);

    answerCache.set(
        key,
        {
            answer,
            time: Date.now()
        }
    );

}


