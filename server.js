async function generateWithRetry(
    modelName,
    message,
    maxRetries = 2
) {

    const model =
        genAI.getGenerativeModel({

            model: modelName,

            systemInstruction:
                DCM_KNOWLEDGE

        });


    let lastError = null;


    for (
        let attempt = 0;
        attempt <= maxRetries;
        attempt++
    ) {

        try {

            console.log(
                `[Gemini] ${modelName} attempt ${attempt + 1}/${maxRetries + 1}`
            );


            const result =
                await model.generateContent(
                    message
                );


            const reply =
                result?.response?.text?.();


            if (!reply) {

                throw new Error(
                    "Gemini returned an empty response"
                );

            }


            console.log(
                `[Gemini] ${modelName} SUCCESS`
            );


            return reply;

        }

        catch (error) {

            lastError =
                error;


            console.error(
                `[Gemini] ${modelName} attempt ${attempt + 1} FAILED`
            );


            console.error(
                error?.message ||
                error
            );


            // ---------------------------------------
            // ถ้าเป็น Error ที่ไม่ควร Retry
            // ---------------------------------------

            if (
                !isRetryableError(error)
            ) {

                throw error;

            }


            // ---------------------------------------
            // ถ้ายังเหลือรอบ
            // ---------------------------------------

            if (
                attempt < maxRetries
            ) {

                /*
                 Exponential Backoff

                 รอบ 1:
                 ประมาณ 2 วินาที

                 รอบ 2:
                 ประมาณ 4 วินาที

                 + random jitter
                */

                const baseDelay =
                    Math.min(
                        2000 *
                        Math.pow(
                            2,
                            attempt
                        ),
                        15000
                    );


                const jitter =
                    Math.floor(
                        Math.random() *
                        1500
                    );


                const delay =
                    baseDelay +
                    jitter;


                console.log(
                    `[Gemini] Retry in ${delay}ms`
                );


                await sleep(
                    delay
                );

            }

        }

    }


    throw lastError;

}


