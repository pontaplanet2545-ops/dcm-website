function getRelevantKnowledge(message) {

    const q =
        normalizeText(message);


    let result = "";


    // หลักสูตร

    if (
        q.includes("หลักสูตร") ||
        q.includes("เรียน") ||
        q.includes("วิชา") ||
        q.includes("หน่วยกิต") ||
        q.includes("โครงสร้าง")
    ) {

        result += DCM_OFFICIAL;

    }


    // อาชีพ

    if (
        q.includes("งาน") ||
        q.includes("อาชีพ") ||
        q.includes("เงินเดือน") ||
        q.includes("content") ||
        q.includes("web") ||
        q.includes("designer") ||
        q.includes("marketing")
    ) {

        result += CAREER_KNOWLEDGE;

    }


    // มหาวิทยาลัย

    if (
        q.includes("มหาวิทยาลัย") ||
        q.includes("วลัยลักษณ์") ||
        q.includes("สมัคร") ||
        q.includes("รับสมัคร") ||
        q.includes("ข่าว") ||
        q.includes("กิจกรรม") ||
        q.includes("ทุน")
    ) {

        result += UNIVERSITY_KNOWLEDGE;

    }


    // ถ้าไม่เข้า category
    // ใช้ข้อมูลสรุป

    if (!result) {

        result = `
ข้อมูลสำคัญของ DCM:

${DCM_OFFICIAL}

${CAREER_KNOWLEDGE}
`;

    }


    return result;

}


