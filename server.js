            // EMPTY
            // =========================================

            if (!message) {

                return res.status(400).json({

                    success: false,

                    error:
                        "กรุณาพิมพ์ข้อความก่อนครับ"

                });

            }


            // =========================================
            // CACHE
            // =========================================

            const cached =
                getCache(message);


            if (cached) {

                return res.json({

                    success: true,

                    reply: cached,

                    source:
                        "cache"

                });

            }


            // =========================================
            // QUICK ANSWER
            // =========================================

            const local =
                quickAnswer(message);


            if (local) {

                setCache(
                    message,
                    local
                );


                return res.json({

                    success: true,

                    reply: local,

                    source:
                        "local"

                });

            }


            // =========================================
            // GEMINI CHECK
            // =========================================

            if (!ai) {

                return res.status(503).json({

                    success: false,

                    error:
                        "ยังไม่ได้ตั้งค่า GEMINI_API_KEY บน Render"

                });

            }


            // =========================================
            // ONLY RELEVANT KNOWLEDGE
            // =========================================

            const relevantKnowledge =
                getRelevantKnowledge(message);


