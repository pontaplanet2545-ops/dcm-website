app.post(
    "/api/chat",
    async (req, res) => {

        try {

            const message =
                String(
                    req.body?.message ||
                    ""
                ).trim();


            // -----------------------------------------
            // EMPTY MESSAGE
            // -----------------------------------------

            if (!message) {

                return res.status(400).json({

                    success: false,

                    error:
                        "กรุณาพิมพ์ข้อความก่อนครับ"

                });

            }


            // -----------------------------------------
            // API KEY CHECK
            // -----------------------------------------

            if (!genAI) {

                return res.status(503).json({

                    success: false,

                    error:
                        "ระบบ AI ยังไม่ได้ตั้งค่า GEMINI_API_KEY บน Render"

                });

            }


            console.log(
                "======================================"
            );

            console.log(
                "[CHAT] New question"
            );

            console.log(
                message
            );

            console.log(
                "======================================"
            );


            // -----------------------------------------
            // ASK GEMINI
            // -----------------------------------------

            const reply =
                await generateGeminiAnswer(
                    message
                );


            // -----------------------------------------
            // SEND RESPONSE
            // -----------------------------------------

            return res.json({

                success: true,

                reply: reply

            });

        }

        catch (error) {

            console.error(
                "======================================"
            );

            console.error(
                "[CHAT ERROR]"
            );

            console.error(
                error
            );

            console.error(
                "======================================"
            );


            const errorMessage =
                String(
                    error?.message ||
                    error ||
                    ""
                );


            // -----------------------------------------
            // SERVICE UNAVAILABLE
            // -----------------------------------------

            if (

                errorMessage.includes("503") ||

                errorMessage.includes(
                    "Service Unavailable"
                ) ||

                errorMessage.includes(
                    "high demand"
                ) ||

                errorMessage.includes(
                    "All Gemini models"
                )

            ) {

                return res.status(503).json({

                    success: false,

                    error:
                        "ตอนนี้ระบบ AI มีผู้ใช้งานจำนวนมากครับ ระบบลองเชื่อมต่อให้อัตโนมัติแล้ว แต่ยังไม่สำเร็จ กรุณาลองใหม่อีกครั้งครับ"

                });

            }


            // -----------------------------------------
            // OTHER ERROR
            // -----------------------------------------

            return res.status(500).json({

                success: false,

                error:
                    "เกิดข้อผิดพลาดในการเชื่อมต่อระบบ AI ครับ"

            });

        }

    }
);


