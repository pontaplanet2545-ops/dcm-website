/* =========================================================
   CHAT API
========================================================= */

app.post(
    "/api/chat",
    async (req, res) => {

        try {

            const message =
                String(
                    req.body?.message || ""
                ).trim();


            /* -----------------------------------------
               CHECK EMPTY
            ----------------------------------------- */

            if(!message){

                return res.status(400).json({

                    success: false,

                    error:
                        "กรุณาพิมพ์ข้อความก่อนครับ"

                });

            }


            /* -----------------------------------------
               QUICK GREETING
            ----------------------------------------- */

            const quickReply =
                getQuickReply(message);


            if(quickReply){

                return res.json({

                    success: true,

                    reply:
                        quickReply,

                    source:
                        "quick-reply"

                });

            }


            /* -----------------------------------------
               CHECK API KEY
            ----------------------------------------- */

            if(!genAI){

                return res.status(503).json({

                    success: false,

                    error:
                        "ยังไม่ได้ตั้งค่า GEMINI_API_KEY"

                });

            }


            /* -----------------------------------------
               GEMINI MODEL
            ----------------------------------------- */

            const model =
                genAI.getGenerativeModel({

                    model:
                        "gemini-3.8-flash",

                    systemInstruction:
                        DCM_KNOWLEDGE,

                    generationConfig: {

                        temperature:
                            0.3,

                        maxOutputTokens:
                            700

                    }

                });


            /* -----------------------------------------
               GENERATE
            ----------------------------------------- */

            const result =
                await model.generateContent(
                    message
                );


            const reply =
                result.response.text();


            /* -----------------------------------------
               RETURN
            ----------------------------------------- */

            return res.json({

                success: true,

                reply:
                    reply,

                source:
                    "gemini"

            });


        } catch(error) {

            console.error(
                "Gemini Error:",
                error
            );


            /* -----------------------------------------
               RATE LIMIT / HIGH DEMAND
            ----------------------------------------- */

            const errorText =
                String(
                    error?.message ||
                    error ||
                    ""
                );


            if(
                errorText.includes("429") ||
                errorText.includes("quota")
            ){

                return res.status(429).json({

                    success: false,

                    error:
                        "ตอนนี้ระบบ AI ใช้งานครบโควตาชั่วคราวครับ กรุณาลองใหม่อีกครั้ง"

                });

            }


            if(
                errorText.includes("503") ||
                errorText.includes("overloaded") ||
                errorText.includes("high demand")
            ){

                return res.status(503).json({

                    success: false,

                    error:
                        "ตอนนี้ Gemini มีผู้ใช้งานจำนวนมากครับ กรุณาลองใหม่อีกครั้ง"

                });

            }


            /* -----------------------------------------
               GENERAL ERROR
            ----------------------------------------- */

            return res.status(500).json({

                success: false,

                error:
                    "เกิดข้อผิดพลาดในการเชื่อมต่อ Gemini"

            });

        }

    }
);


